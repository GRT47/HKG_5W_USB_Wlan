        "        if [ -n \"$STA_PASS\" ]; then\n"
        "            cat >> \"$WIFI_WORK_DIR/wpa_supplicant.conf\" <<EOF\n"
        "network={\n"
        "    ssid=\"$STA_SSID\"\n"
        "    scan_ssid=1\n"
        "    key_mgmt=WPA-PSK\n"
        "    psk=\"$STA_PASS\"\n"
        "    priority=100\n"
        "}\n"
