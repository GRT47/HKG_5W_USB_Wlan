        "                [ -n \"$_s_ssid\" ] || continue\n"
        "                [ \"$_s_ssid\" = \"$STA_SSID\" ] && continue\n"
        "                _prio=$((_prio - 10))\n"
        "                [ \"$_prio\" -lt 10 ] && _prio=10\n"
