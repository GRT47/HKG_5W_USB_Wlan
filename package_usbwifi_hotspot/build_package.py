        "is_sta_healthy() {\n"
        "    local _iface=\"$1\" _wpid _cpid _sta_ip _gw _dns1 _assoc=0 _rproc\n"
        "    [ -n \"$_iface\" ] || return 1\n"
        "    [ -d \"/sys/class/net/$_iface\" ] || return 1\n"
