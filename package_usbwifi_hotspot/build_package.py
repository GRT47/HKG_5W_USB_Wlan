        "    ssid=\"$STA_SSID\"\n"
        "    scan_ssid=1\n"
        "    key_mgmt=NONE\n"
        "    priority=100\n"
        "}\n"
        "EOF\n"
        "        fi\n"
        "        if [ -f \"$SAVED_STA_FILE\" ]; then\n"
